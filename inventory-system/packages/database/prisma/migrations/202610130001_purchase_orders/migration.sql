CREATE TABLE `purchase_orders` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `order_no` VARCHAR(40) NOT NULL,
  `organization_id` BIGINT UNSIGNED NOT NULL,
  `store_id` BIGINT UNSIGNED NOT NULL,
  `week_start` DATE NOT NULL,
  `status` ENUM('DRAFT','CONFIRMED','ORDERED','PARTIALLY_RECEIVED','RECEIVED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  `notes` VARCHAR(500) NULL,
  `created_by` BIGINT UNSIGNED NOT NULL,
  `confirmed_by` BIGINT UNSIGNED NULL,
  `confirmed_at` DATETIME(3) NULL,
  `ordered_by` BIGINT UNSIGNED NULL,
  `ordered_at` DATETIME(3) NULL,
  `cancelled_by` BIGINT UNSIGNED NULL,
  `cancelled_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `purchase_orders_order_no_key`(`order_no`),
  UNIQUE INDEX `purchase_orders_organization_id_store_id_week_start_key`(`organization_id`,`store_id`,`week_start`),
  INDEX `purchase_orders_store_id_status_week_start_idx`(`store_id`,`status`,`week_start`),
  PRIMARY KEY (`id`),
  CONSTRAINT `purchase_orders_organization_id_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `purchase_orders_store_id_fkey` FOREIGN KEY (`store_id`) REFERENCES `stores`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `purchase_orders_created_by_fkey` FOREIGN KEY (`created_by`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `purchase_orders_confirmed_by_fkey` FOREIGN KEY (`confirmed_by`) REFERENCES `users`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `purchase_orders_ordered_by_fkey` FOREIGN KEY (`ordered_by`) REFERENCES `users`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `purchase_orders_cancelled_by_fkey` FOREIGN KEY (`cancelled_by`) REFERENCES `users`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `purchase_order_items` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `purchase_order_id` BIGINT UNSIGNED NOT NULL,
  `product_id` BIGINT UNSIGNED NOT NULL,
  `source` ENUM('MANUAL','OUT_OF_STOCK','LOW_STOCK','HOT_SALES','WEEKLY_FORECAST') NOT NULL DEFAULT 'MANUAL',
  `current_inventory` INTEGER NOT NULL,
  `recent_seven_day_qty` INTEGER NOT NULL DEFAULT 0,
  `suggested_quantity` INTEGER NOT NULL,
  `ordered_quantity` INTEGER NOT NULL,
  `received_quantity` INTEGER NOT NULL DEFAULT 0,
  `supplier_name` VARCHAR(120) NULL,
  `unit_cost_cents` INTEGER NULL,
  `case_size` INTEGER NULL,
  `notes` VARCHAR(255) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `purchase_order_items_purchase_order_id_product_id_key`(`purchase_order_id`,`product_id`),
  INDEX `purchase_order_items_product_id_created_at_idx`(`product_id`,`created_at`),
  PRIMARY KEY (`id`),
  CONSTRAINT `purchase_order_items_purchase_order_id_fkey` FOREIGN KEY (`purchase_order_id`) REFERENCES `purchase_orders`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `purchase_order_items_product_id_fkey` FOREIGN KEY (`product_id`) REFERENCES `products`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `purchase_order_items_quantity_check` CHECK (`suggested_quantity` >= 0 AND `ordered_quantity` > 0 AND `received_quantity` >= 0 AND `received_quantity` <= `ordered_quantity`),
  CONSTRAINT `purchase_order_items_cost_check` CHECK (`unit_cost_cents` IS NULL OR `unit_cost_cents` >= 0),
  CONSTRAINT `purchase_order_items_case_size_check` CHECK (`case_size` IS NULL OR `case_size` > 0)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
